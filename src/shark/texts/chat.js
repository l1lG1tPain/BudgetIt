/** Отклик на имя: характер, настроение карточки (new/ok/tense/angry/proud) и болтливость (quiet/normal/chatty) */
export function callLine(character = 'normal', mood = 'ok', talk = 'normal', seed = Math.random(), shout = false) {
    const ch = CALL_TEXTS[character] ? character : 'normal';
    const set = shout ? CALL_SHOUT : CALL_TEXTS;
    const pool = talk === 'quiet' ? CALL_QUIET[ch] : (set[ch][mood] || set[ch].ok);
    return pool[Math.min(pool.length - 1, Math.floor(seed * pool.length))];
}


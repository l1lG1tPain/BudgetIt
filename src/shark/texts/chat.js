const CHARS = ['kind', 'normal', 'strict'];

/** Фраза по виду и характеру; seed делает выбор повторяемым (для тестов). */
export function chatLine(kind, character = 'normal', vars = {}, seed = Math.random()) {
    const pool = CHAT_TEXTS[kind]?.[CHARS.includes(character) ? character : 'normal'] || [];
    if (!pool.length) return '';
    const s = typeof seed === 'number' ? seed : [...String(seed)].reduce((a, c) => (a * 31 + c.charCodeAt(0)) % 997, 7) / 997;
    const raw = pool[Math.min(pool.length - 1, Math.floor(s * pool.length))];
    // пустые подстановки не оставляют «, ,» и пустых кавычек: «Записала: 50 000, 23.11.2026.»
    return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''))
        .replace(/«\s*»/g, '').replace(/(?:,\s*){2,}/g, ', ').replace(/,\s*(?=[.!?]|$)/g, '').replace(/:\s*,\s*/g, ': ').replace(/ {2,}/g, ' ').trim();
}
